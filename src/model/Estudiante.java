package model;

public class Estudiante {

    private String legajo;
    private String nombre;
    private String carrera;
    private String mail;

    
    public Estudiante(String legajo, String nombre, String carrera, String mail) {
        this.legajo = legajo;
        this.nombre = nombre;
        this.carrera = carrera;
        this.mail = mail;
    }

    
    
}
